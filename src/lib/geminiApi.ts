import { getBackendUrl } from './apiConfig';

const BACKEND_URL = getBackendUrl();

export interface QuestionSimple {
  id: number;
  question: string;
  answer: string;
  importance_stars?: number;
  priority_tag?: string;
}

export interface Question8MarkAnswer {
  definition?: string;
  architecture_structure?: string;
  operations?: string;
  program_code?: string;
  program_output?: string;
  advantages_disadvantages?: string;
}

export interface Question8Mark {
  id: number;
  question: string;
  importance_stars?: number;
  priority_tag?: string;
  answer: string | Question8MarkAnswer;
}

export interface Question12Mark {
  id: number;
  question: string;
  importance_stars?: number;
  priority_tag?: string;
  answer: {
    // 7-Part Professional University Exam Sheet Structure
    introduction?: string;
    architecture_types?: string;
    concrete_example?: string;
    program_code?: string;
    program_output?: string;
    numerical_problem?: string;
    tradeoffs_complexity?: string;
    // Legacy compatibility fields
    headings?: Array<{
      title: string;
      content: string;
    }>;
    examples?: string;
    conclusion?: string;
  };
}

export interface GeminiExamQAResponse {
  success: boolean;
  provider: string;
  chapter_title: string;
  summary: string;
  questions_1mark?: QuestionSimple[];
  questions_2mark: QuestionSimple[];
  questions_3mark: QuestionSimple[];
  questions_5mark?: QuestionSimple[];
  questions_8mark?: Question8Mark[];
  questions_12mark: Question12Mark[];
}

export interface GeminiStoryResponse {
  success: boolean;
  provider: string;
  title: string;
  simple_explanation: string;
  story: string;
  audio_script: string;
}

/**
 * Fetch 1-mark, 2-mark, 5-mark, and 12-mark exam questions and detailed answers
 * generated by Google Gemini AI from the uploaded syllabus/theory PDF text.
 *
 * @param prompt - Full extracted text of the document
 * @param language - Target language: 'en' (English) or 'ta' (Tamil)
 */
export async function fetchGeminiExamQA(
  prompt: string,
  language: 'en' | 'ta' = 'en'
): Promise<GeminiExamQAResponse> {
  let response: Response;

  try {
    response = await fetch(`${BACKEND_URL}/api/gemini/exam-qa`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ prompt, language }),
    });
  } catch {
    throw new Error(
      'Cannot connect to the backend server. Make sure the EduMind backend service is running and accessible.'
    );
  }

  if (!response.ok) {
    const errorBody = await response.json().catch(() => ({}));
    throw new Error(
      (errorBody as { message?: string }).message ||
        `Gemini API error (HTTP ${response.status})`
    );
  }

  const data: GeminiExamQAResponse = await response.json();
  if (!data.success) {
    throw new Error('Gemini AI service returned an unsuccessful response.');
  }

  if (!data.questions_8mark) {
    data.questions_8mark = data.questions_5mark || [];
  }

  return data;
}

/**
 * Convert academic theory into an easy simplified explanation and creative story
 * for audio playback and speech synthesis.
 */
export async function fetchGeminiStory(
  text: string,
  language: 'en' | 'ta' = 'ta'
): Promise<GeminiStoryResponse> {
  let response: Response;
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 18000);

  try {
    response = await fetch(`${BACKEND_URL}/api/gemini/story-convert`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, language }),
      signal: controller.signal,
    });
  } catch (err: unknown) {
    clearTimeout(timeoutId);
    if ((err as { name?: string })?.name === 'AbortError') {
      throw new Error('Story generation request timed out. Switched to instant syllabus lesson.');
    }
    throw new Error(
      'Cannot connect to the backend server for story conversion.'
    );
  } finally {
    clearTimeout(timeoutId);
  }

  if (!response.ok) {
    const errorBody = await response.json().catch(() => ({}));
    throw new Error(
      (errorBody as { message?: string }).message ||
        `Gemini story API error (HTTP ${response.status})`
    );
  }

  return await response.json();
}

/**
 * Synthesize studio-quality conversational neural audio for Tamil and English.
 * - Tamil: Warm, engaging story voice ('ta-IN-PallaviNeural')
 * - English: Soft, sweet, expressive human tutor voice ('en-US-JennyNeural')
 *
 * @returns Blob of audio/mpeg
 */
export async function fetchSynthesizedSpeech(
  text: string,
  language: 'en' | 'ta' = 'ta',
  mode: 'story' | 'tutor' = 'story'
): Promise<Blob> {
  let response: Response;
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 15000);

  try {
    response = await fetch(`${BACKEND_URL}/api/gemini/synthesize-speech`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, language, mode }),
      signal: controller.signal,
    });
  } catch (err: unknown) {
    clearTimeout(timeoutId);
    if ((err as { name?: string })?.name === 'AbortError') {
      throw new Error('Speech synthesis timed out. Using browser voice fallback.');
    }
    throw new Error(
      'Cannot connect to the backend speech synthesis server.'
    );
  } finally {
    clearTimeout(timeoutId);
  }

  if (!response.ok) {
    const errorBody = await response.json().catch(() => ({}));
    throw new Error(
      (errorBody as { message?: string }).message ||
        `Speech synthesis failed (HTTP ${response.status})`
    );
  }

  return await response.blob();
}

export interface GeminiChatResponse {
  success: boolean;
  provider: string;
  answer: string;
}

/**
 * Interactive Gemini AI Study Assistant Chat.
 * Ask custom definitions, programming code, derivations, or 12-mark essay answers.
 */
export async function fetchGeminiChat(
  query: string,
  context?: string,
  language: 'en' | 'ta' = 'en'
): Promise<string> {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 20000);

  try {
    const res = await fetch(`${BACKEND_URL}/api/gemini/chat`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ query, context, language }),
      signal: controller.signal,
    });
    clearTimeout(timeoutId);

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.message || `AI Chat request failed (${res.status})`);
    }

    const data: GeminiChatResponse = await res.json();
    return data.answer || 'No response generated.';
  } catch (err: unknown) {
    clearTimeout(timeoutId);
    if ((err as { name?: string })?.name === 'AbortError') {
      throw new Error('Gemini AI assistant response took too long. Please try again.');
    }
    throw err;
  }
}


